// Generates a slim, drop-in replacement for lucide.min.js containing ONLY the
// icons actually referenced by the app. The full library (~409 KB) ships every
// icon; the app uses ~50. We keep the upstream build in vendor/ and extract the
// icon data from it, then emit a faithful (vendor-derived) runtime + subset.
//
// Run after changing icon usage:  node build-lucide-subset.mjs
//
// Safety net: if any referenced icon name cannot be resolved against the
// upstream registry, the build FAILS loudly instead of silently dropping it.

import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const FULL = 'vendor/lucide.full.min.js';
const OUT = 'lucide.min.js';

// Files to scan for icon usage.
const SCAN_FILES = [
  'index.html',
  'src/app/00-config-state.js',
  'src/app/04-models-entry-utils.js',
  'src/app/08-layout-preview-controls.js',
  'src/app/09-import-export-theme.js',
  'src/app/10-editor-mode-assets.js',
  'src/app/11-explorer-tabs.js',
  'src/app/12-mobile-init.js',
  'src/app/13-about-panel.js',
];

// Icons returned dynamically by getIconForFilename() — not literal data-lucide
// attributes, so they must be listed explicitly.
const DYNAMIC_ICONS = [
  'code-2', 'palette', 'braces', 'file-json', 'file-text',
  'image', 'type', 'music', 'film', 'folder', 'folder-open',
  'check-circle', 'alert-circle',
];

function collectIconNames(sources) {
  const names = new Set(DYNAMIC_ICONS);
  const patterns = [
    /data-lucide=["']([a-z0-9-]+)["']/g,                       // <i data-lucide="x">
    /setAttribute\(\s*["']data-lucide["']\s*,\s*["']([a-z0-9-]+)["']\s*\)/g, // setAttribute
    /\bicon:\s*["']([a-z0-9-]+)["']/g,                          // { icon: 'x' } config
  ];
  for (const src of sources) {
    for (const re of patterns) {
      let m;
      while ((m = re.exec(src))) names.add(m[1]);
    }
  }
  return [...names].sort();
}

// kebab-case -> PascalCase, matching lucide's own toPascalCase.
function toPascalCase(str) {
  const camel = str.replace(/^([A-Z])|[\s-_]+(\w)/g, (_, a, b) =>
    b ? b.toUpperCase() : a.toLowerCase());
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

async function extractRegistry() {
  const code = await readFile(FULL, 'utf8');
  const exportsObj = {};
  const sandbox = {
    exports: exportsObj,
    module: { exports: exportsObj },
    define: undefined,
    document: undefined,
    globalThis: {},
  };
  sandbox.self = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: FULL });
  if (!exportsObj.icons || typeof exportsObj.icons !== 'object') {
    throw new Error('Could not extract `icons` registry from ' + FULL);
  }
  return exportsObj.icons;
}

const sources = await Promise.all(SCAN_FILES.map((f) => readFile(f, 'utf8')));
const kebabNames = collectIconNames(sources);
const registry = await extractRegistry();

const subset = {};
const missing = [];
for (const kebab of kebabNames) {
  const pascal = toPascalCase(kebab);
  if (registry[pascal]) subset[pascal] = registry[pascal];
  else missing.push(`${kebab} (looked up as ${pascal})`);
}

if (missing.length) {
  console.error('✗ Icons referenced but NOT found in lucide registry:');
  missing.forEach((m) => console.error('   - ' + m));
  process.exit(1);
}

// Faithful runtime derived from lucide v1.21 (createElement / createIcons).
// Behaviour-identical to upstream for the data-lucide replacement path.
const runtime = `/* Generated by build-lucide-subset.mjs from ${FULL}.
 * Subset of lucide (ISC). Contains only the icons used by the app.
 * Re-run: node build-lucide-subset.mjs */
(function (root, factory) {
  if (typeof exports === "object" && typeof module !== "undefined") factory(exports);
  else if (typeof define === "function" && define.amd) define(["exports"], factory);
  else factory((root.lucide = root.lucide || {}));
})(typeof globalThis !== "undefined" ? globalThis : this, function (a) {
  "use strict";
  var defaultAttrs = { xmlns: "http://www.w3.org/2000/svg", width: 24, height: 24, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round" };
  var icons = ICONS_PLACEHOLDER;
  function createNode(node) {
    var tag = node[0], attrs = node[1], children = node[2];
    var el = document.createElementNS("http://www.w3.org/2000/svg", tag);
    Object.keys(attrs).forEach(function (k) { el.setAttribute(k, String(attrs[k])); });
    if (children && children.length) children.forEach(function (c) { el.appendChild(createNode(c)); });
    return el;
  }
  function createElement(iconNode, attrs) {
    return createNode(["svg", Object.assign({}, defaultAttrs, attrs || {}), iconNode]);
  }
  function hasA11yProp(attrs) {
    for (var k in attrs) if (k.indexOf("aria-") === 0 || k === "role" || k === "title") return true;
    return false;
  }
  function combineClasses() {
    var parts = [].slice.call(arguments);
    return parts.filter(function (c, i, arr) { return !!c && c.trim() !== "" && arr.indexOf(c) === i; }).join(" ").trim();
  }
  function toCamelCase(s) {
    return s.replace(/^([A-Z])|[\\s-_]+(\\w)/g, function (_, x, y) { return y ? y.toUpperCase() : x.toLowerCase(); });
  }
  function toPascalCase(s) { var c = toCamelCase(s); return c.charAt(0).toUpperCase() + c.slice(1); }
  function getAttrs(el) {
    return Array.prototype.slice.call(el.attributes).reduce(function (acc, at) { acc[at.name] = at.value; return acc; }, {});
  }
  function getClassNames(attr) {
    if (typeof attr === "string") return attr;
    if (!attr || !attr.class) return "";
    if (typeof attr.class === "string") return attr.class.split(" ");
    if (Array.isArray(attr.class)) return attr.class;
    return "";
  }
  function replaceElement(el, opts) {
    var nameAttr = opts.nameAttr, iconsObj = opts.icons, extraAttrs = opts.attrs;
    var name = el.getAttribute(nameAttr);
    if (name == null) return;
    var node = iconsObj[toPascalCase(name)];
    if (!node) { console.warn(el.outerHTML + " icon name was not found in the provided icons object."); return; }
    var elAttrs = getAttrs(el);
    var a11y = hasA11yProp(elAttrs) ? {} : { "aria-hidden": "true" };
    var finalAttrs = Object.assign({}, defaultAttrs, { "data-lucide": name }, a11y, extraAttrs, elAttrs);
    var merged = combineClasses.apply(null, ["lucide", "lucide-" + name]
      .concat(getClassNames(elAttrs)).concat(getClassNames(extraAttrs)));
    if (merged) finalAttrs.class = merged;
    var svg = createElement(node, finalAttrs);
    if (el.parentNode) el.parentNode.replaceChild(svg, el);
  }
  function createIcons(options) {
    options = options || {};
    var iconsObj = options.icons || icons;
    var nameAttr = options.nameAttr || "data-lucide";
    var extraAttrs = options.attrs || {};
    var root = options.root || document;
    if (typeof root === "undefined") throw new Error("\`createIcons()\` only works in a browser environment.");
    Array.prototype.slice.call(root.querySelectorAll("[" + nameAttr + "]")).forEach(function (el) {
      replaceElement(el, { nameAttr: nameAttr, icons: iconsObj, attrs: extraAttrs });
    });
  }
  Object.keys(icons).forEach(function (k) { a[k] = icons[k]; });
  a.createElement = createElement;
  a.createIcons = createIcons;
  a.icons = icons;
});
`;

const out = runtime.replace('ICONS_PLACEHOLDER', JSON.stringify(subset));
await writeFile(OUT, out, 'utf8');

const { size: fullSize } = await readFile(FULL).then((b) => ({ size: b.length }));
const newSize = Buffer.byteLength(out, 'utf8');
console.log(
  `Built ${OUT} with ${Object.keys(subset).length} icons: ` +
  `${(newSize / 1024).toFixed(1)} KB (was ${(fullSize / 1024).toFixed(1)} KB, ` +
  `-${(100 - (newSize / fullSize) * 100).toFixed(1)}%).`
);
